def kyote_months(units):
    """ガイドの標準時期（7〜12月）を、試作の方針どおり 9〜12月 に詰める：
    練成は 9月・10月 に前半・後半で分け、実戦は 11月・12月 に前半・後半で分ける。"""
    ren = [units[m] for m in sorted(units) if units[m].startswith("練成")]
    jit = [units[m] for m in sorted(units) if units[m].startswith("実戦")]

    def split(xs):
        if not xs:
            return "", ""
        if len(xs) == 1:
            return xs[0], ""
        h = (len(xs) + 1) // 2
        return _join_units(xs[:h]), _join_units(xs[h:])

    a, b = split(ren)
    c, d = split(jit)
    return [a, b, c, d]


def kyote_rows():
    """共テDB の行：(科目欄, 講座名, 9月, 10月, 11月, 12月, 項目, パターン)
    パターンごとに、ガイドの一覧に載っている講座を載せる（同じ項目に学研とアドバンスの両方があれば先に載っている方。
    英語のリスニング 3ELQ は別に載せる）。"""
    rows = []
    for p in patterns():
        seen = set()
        for code in p["kyote"]:
            if code not in KYOTE_UNITS:
                continue
            blk, item, name, units = KYOTE_UNITS[code]
            key = (item, "L" if code == "3ELQ" else "")
            if key in seen:
                continue
            seen.add(key)
            rows.append((blk, name, *kyote_months(units), item, p["name"]))
    return rows


