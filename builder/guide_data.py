def system_of(name):
    """パターン名 → 系統（国立文系 / 国立理系 / 私大文系 / 私大理系）"""
    kubun = "国立" if "国公立" in name else "私大"
    bunri = "文系" if "文系" in name else "理系"
    return kubun + bunri


def tier_of(name):
    """教材の難易度に使うレベル"""
    return "難関" if any(k in name for k in ("最難関", "難関", "医学部")) else "標準"


def _join_units(labels):
    """同じマスに入るユニットをまとめる：練成1+練成2 → 練成1・2"""
    labels = [x for x in labels if x]
    if len(labels) <= 1:
        return labels[0] if labels else ""
    m = [re.fullmatch(r"(\D+)(\d+)", x) for x in labels]
    if all(m) and len({x.group(1) for x in m}) == 1:
        return m[0].group(1) + "・".join(x.group(2) for x in m)
    return "・".join(labels)


def _alt_cells(alt):
    """1つの講座（上段/下段）→ 講座の帯（17マス、←は結合）と受講回（17マス）"""
    band = [""] * 17
    kai_parts = [[] for _ in range(17)]
    star = set()
    for half in ("left", "right"):
        h = alt[half]
        for b in h.get("bands", []):
            idx = sorted({PERIOD_INDEX[p] for p in b["periods"]})
            if not idx:
                continue
            text = (b["code"] + "　" + b["title"]).strip()
            a, e = idx[0], idx[-1]
            if band[a] and band[a] != "←" and text not in band[a]:
                band[a] = band[a] + "／" + text
            elif not band[a] or band[a] == "←":
                band[a] = text
            for i in range(a + 1, e + 1):
                if not band[i]:
                    band[i] = "←"
            for p in sorted(b["units"], key=PERIOD_ORDER.index):
                kai_parts[PERIOD_INDEX[p]].append(b["units"][p].replace(" ", ""))
        for p in h.get("star", []):
            star.add(PERIOD_INDEX[p])
    kai = []
    for i in range(17):
        k = _join_units(kai_parts[i])
        kai.append(k if k else ("※" if i in star else ""))
    return band, kai


def patterns():
    """[{name, system, tier, pages, universities:[...], blocks:{科目欄:{上段:(band,kai), 下段:(band,kai)}},
         alternatives:{科目欄:[講座名,...]}, kyote:[code,...]}]"""
    out = []
    for p in _load():
        name = p["name"]
        uni = UNIV_FIX.get(name, p["universities"])
        blocks, alts = {}, {}
        for s in p["subjects"]:
            blk = BLOCK_OF.get(s["label"])
            if not blk or not s["alternatives"]:
                continue
            cells = [_alt_cells(a) for a in s["alternatives"]]
            blocks[blk] = {"上段": cells[0], "下段": cells[1] if len(cells) > 1 else cells[0]}
            if len(cells) > 1:
                alts[blk] = [next((c for c in cell[0] if c and c != "←"), "") for cell in cells]
        out.append(dict(name=name, system=system_of(name), tier=tier_of(name), pages=p["pages"],
                        universities=uni, blocks=blocks, alternatives=alts, kyote=p["kyote"]))
    return out


def university_names(text):
    """「一橋/大阪/…/他」→ ['一橋大学', '大阪大学', …]（（難関）などの注記・『他』は除く）"""
    text = re.sub(r"【[^】]*】", "/", text)
    text = re.sub(r"（[^）]*）", "/", text)
    out = []
    for t in text.split("/"):
        t = t.strip()
        if not t or t in ("他",) or "医学部医学科" in t:
            continue
        if not t.endswith("大学"):
            t = t + "大学"
        if t not in out:
            out.append(t)
    return out


