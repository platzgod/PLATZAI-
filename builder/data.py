def pick(table, subj, level, kubun, bunri):
    """(科目, レベル, 区分, 文理) に最もよく合う値を返す（* はワイルドカード）。"""
    best, best_score = None, -1
    for (s, lv, kb, br), v in table.items():
        if s != subj:
            continue
        if lv not in ("*", level) or kb not in ("*", kubun) or br not in ("*", bunri):
            continue
        score = (lv != "*") * 4 + (kb != "*") * 2 + (br != "*")
        if score > best_score:
            best, best_score = v, score
    return best


def build_db():
    """カリキュラムDB の行を作る: [(系統, 科目, レベル, 種別, [17セル])]"""
    rows = []
    for system in SYSTEMS:
        kubun, bunri = system[:2], system[2:]
        for subj in KOBETSU_SUBJECTS[system]:
            for level in LEVELS:
                course = pick(COURSES, subj, level, kubun, bunri)
                assert course, (system, subj, level)
                band = [""] * NPER
                title = (course["code"] + "　" if course["code"] else "") + course["name"]
                _fill(band, 1, 8, title)
                if course["summer"]:
                    _fill(band, 9, 10, ("N" + course["code"]) if course["code"] else "夏期講習")
                _fill(band, 11, 14, title)
                if course["chokuzen"]:
                    _fill(band, 15, 16, ("F" + course["code"]) if course["code"] else "直前講習")
                kai = list(course["kai_pre"]) + list(course["kai_post"])
                assert len(kai) == NPER
                juku = [""] * NPER
                for a, b, t in pick(JUKU, subj, level, kubun, bunri) or []:
                    _fill(juku, a, b, t)
                if juku[0] == "" and subj in ("英語", "数学", "現代文", "古文"):
                    juku[0] = "【塾】高2範囲の総復習・診断"
                ie = [""] * NPER
                for a, b, t in pick(IE, subj, level, kubun, bunri) or []:
                    _fill(ie, a, b, t)
                if kubun == "私大":
                    juku = [_shidai(t) for t in juku]
                    ie = [_shidai(t) for t in ie]
                for kind, cells in zip(KINDS, (band, kai, juku, ie)):
                    assert cells[SPLIT] != "←", (system, subj, level, kind)
                    rows.append((system, subj, level, kind, cells))
    return rows


def _shidai(t):
    """私大向け: 共通テスト対策の文言を外す（共テ利用は別途 設定で）。"""
    t = t.replace("＋共通テスト過去問", "").replace("＋共通テスト対策", "")
    if t.startswith("【家】共通テスト過去問（"):
        t = "【家】" + t[len("【家】共通テスト過去問（"):-1] + "の問題集で演習"
    if t == "【塾】共通テスト現代文 対策問題集":
        t = "【塾】入試現代文へのアクセス 発展編"
    t = t.replace("共通テスト・志望校過去問", "志望校過去問")
    return t


def _fill(cells, a, b, text):
    assert 0 <= a <= b < NPER
    assert not (a < SPLIT <= b), ("前期と後期をまたいでいます", text)
    for i in range(a, b + 1):
        assert cells[i] == "", ("重複", text)
    cells[a] = text
    for i in range(a + 1, b + 1):
        cells[i] = "←"


